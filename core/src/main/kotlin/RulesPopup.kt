package ru.triplethall.mushroomhunt
import com.badlogic.gdx.scenes.scene2d.ui.*
class RulesPopup(skin: Skin) : Table() {
    init {
        setFillParent(true)
        background(skin.newDrawable("white", 0f, 0f, 0f, 0.6f))
// Многострочный текст. \n\n — пустая строка между абзацами.
        val text = "«Тихая Охота»\n" +
            "Логлайн: Ты заблудился в ночном лесу и наткнулся на костёр. Хозяин костра — леший — предлагает сделку: сыграй в его игру, и он покажет дорогу. На пень высыпается корзина грибов. Часть из них съедобные. Часть — нет.\n" +
            "Ядро геймплея\n" +
            "Работает та же формула напряжения, что в Buckshot Roulette, но вместо дробовика — корзина грибов:\n" +
            "Леший высыпает N грибов и честно объявляет состав: «Шесть грибов: три белых, две поганки, один мухомор»\n" +
            "Съесть гриб самому → если съедобный, ход остаётся у тебя (жадность вознаграждается)\n" +
            "Пододвинуть лешему → если ядовитый, он теряет здоровье, ход переходит к нему\n" +
            "Мухомор = −2 сердца, поганка = −1 сердце. У обоих по 3–5 сердец на раунд\n" +
            "Ключевое отличие от референса: исходов не два, а три-четыре. Математика вероятностей становится интереснее — игрок в уме считает комбинаторику, а не просто «бой/холостой».\n" +
            "Уникальные механики\n" +
            "Галлюцинации. Ложный сморчок выглядит как съедобный, но после него интерфейс начинает врать — метки грибов на экране показывают неправильные типы 2 хода. Игрок должен помнить, чему верить нельзя.\n" +
            "Леший мухлюет. На поздних уровнях экран периодически «мигает» темнотой (как моргание) — и гриб на пне может оказаться подменён.\n" +
            "Нож. Разрезаешь гриб пополам: узнаёшь его тип, но съедаешь половину эффекта. Знание в обмен на урон.\n" +
            "Предметы (по 2–3 слота перед раундом)\n" +
            "Соль — круг из соли: леший пропускает ход (раз за раунд)\n" +
            "Синичка — скормить ей гриб: он исчезает из игры без эффекта\n" +
            "Фляга молока — снять галлюцинацию / +1 сердце\n" +
            "Лупа — подсмотреть, что прячется под шляпкой\n" +
            "Структура\n" +
            "Вместо «этажей» — глубина леса: дальше от костра встречаешь кикимору (подменяет грибы), водяного (грибы «тонут» — их не видно пару ходов), финальный босс — сам Леший. Плюс бесконечный режим с сидом и ежедневный забег с фикс. корзиной для таблицы лидеров.\n" +
            "Мобильные решения\n" +
            "Вертикальный экран, всё управление тапами, сессия 3–5 минут\n" +
            "Вибрация при укусе мухомора, звук сердца и потрескивание костра\n" +
            "Визуал — силуэты на тёплом свете костра, вайб «Ёжика в тумане» и советских мульт-страшилок\n" +
            "Монетизация: премиум без рекламы + косметика (корзины, костры, шляпы грибника)"
        val label = Label(text, skin)
        label.setWrap(true) // ВАЖНО: разрешить перенос строк. Без этого текст уползёт за экран одной
// ScrollPane — «окно» с прокруткой: внутри лента, снаружи рамка.
// В конструктор — контейнер с текстом и стиль из скина.
        val textTable = Table()
        textTable.pad(10f)
        textTable.add(label).width(520f).left() // фиксированная ширина текста, перенос работает по
        val scroll = ScrollPane(textTable, skin)
        val btnClose = GameButton("CLOSE", skin)
        btnClose.onClick = { remove() }
// Карточка
        val box = Table(skin)
        box.background(skin.newDrawable("white", 0.15f, 0.12f, 0.1f, 0.95f))
        box.add(Label("RULES", skin)).pad(16f).row()
        box.add(scroll).pad(10f).size(560f, 300f).row()
        box.add(btnClose).pad(16f).row()
        add(box).expand().center()
    }
}
